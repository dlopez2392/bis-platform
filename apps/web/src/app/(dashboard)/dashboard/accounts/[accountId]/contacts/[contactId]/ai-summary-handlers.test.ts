import { describe, it, expect, vi } from "vitest";
import { loadAiSummary, POLL_LIMIT, POLL_EVERY_MS } from "./ai-summary-handlers";

const READY = { state: "ready", text: "Booked.", generatedAt: "2026-10-18T14:42:00Z", language: "en", stamp: "Generated by AI · 9:42 AM" };
const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });

describe("loadAiSummary (spec 4.5, I4)", () => {
  it("GET once; POST when forced (mutation: always GET -> FAILS)", async () => {
    const seen: string[] = [];
    const f = async (_u: string, init?: RequestInit) => { seen.push(String(init?.method)); return json(READY); };
    expect(await loadAiSummary("/x", { force: false, fetchImpl: f })).toEqual(READY);
    await loadAiSummary("/x", { force: true, fetchImpl: f });
    expect(seen).toEqual(["GET", "POST"]);
  });
  it("re-asks every 2 s while generating, then shows what came (mutation: no wait between asks -> FAILS)", async () => {
    const answers = [{ state: "generating" }, { state: "generating" }, READY];
    const waits: number[] = [];
    const methods: string[] = [];
    const r = await loadAiSummary("/x", { force: true, fetchImpl: async (_u, init) => { methods.push(String(init?.method)); return json(answers.shift()); }, wait: async (ms) => { waits.push(ms); } });
    expect(r).toEqual(READY);
    expect(waits).toEqual([POLL_EVERY_MS, POLL_EVERY_MS]);
    expect(methods).toEqual(["POST", "GET", "GET"]);
  });
  it("gives up after 15 re-asks as failed (mutation: POLL_LIMIT 16 or an endless loop -> FAILS)", async () => {
    let n = 0;
    const r = await loadAiSummary("/x", { force: false, fetchImpl: async () => { n++; return json({ state: "generating" }); }, wait: async () => {} });
    expect([r, n, POLL_LIMIT]).toEqual([{ state: "failed" }, 16, 15]);
  });
  it("an abort during the wait clears its timer and ends at once, with no further ask (final review M-h; mutation: a wait that ignores the signal -> the timer stays and nothing settles -> FAILS)", async () => {
    vi.useFakeTimers();
    try {
      const ac = new AbortController();
      let asks = 0;
      const p = loadAiSummary("/x", { force: false, signal: ac.signal, fetchImpl: async () => { asks++; return json({ state: "generating" }); } });
      let settled = false;
      void p.then(() => { settled = true; });
      await vi.advanceTimersByTimeAsync(0); // the first ask answers; the 2 s wait is scheduled, not run
      expect([vi.getTimerCount(), settled]).toEqual([1, false]);
      ac.abort();
      expect(vi.getTimerCount()).toBe(0);
      await vi.advanceTimersByTimeAsync(0); // microtasks only: the clock does not move
      expect([settled, asks]).toEqual([true, 1]);
    } finally {
      vi.useRealTimers();
    }
  });
  it("a 404, a 500, a throw or a bad body is failed, never a throw (mutation: drop the res.ok check -> the 500's body parses as failed? use a 500 with a READY body -> FAILS)", async () => {
    expect(await loadAiSummary("/x", { force: false, fetchImpl: async () => json(READY, 500) })).toEqual({ state: "failed" });
    expect(await loadAiSummary("/x", { force: false, fetchImpl: async () => json({}, 404) })).toEqual({ state: "failed" });
    expect(await loadAiSummary("/x", { force: false, fetchImpl: async () => { throw new TypeError("network"); } })).toEqual({ state: "failed" });
    expect(await loadAiSummary("/x", { force: false, fetchImpl: async () => json({ state: "maybe" }) })).toEqual({ state: "failed" });
  });
});
