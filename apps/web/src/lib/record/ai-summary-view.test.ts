import { describe, it, expect } from "vitest";
import { aiSummaryStamp, parseAiSummary } from "./ai-summary-view";
import { makeTr } from "./copy";

const ZONE = "America/Chicago";
const NOW = new Date("2026-10-18T22:05:00Z");

describe("the label (spec 4.8; plan deviations 13, 14; assumption A1)", () => {
  it("today: the local time; another day: the date and time; both languages (mutations: format in UTC -> FAILS; drop the same-day branch -> FAILS)", () => {
    expect([
      aiSummaryStamp("2026-10-18T14:42:00Z", { zone: ZONE, now: NOW, tr: makeTr("en") }),
      aiSummaryStamp("2026-10-18T14:42:00Z", { zone: ZONE, now: NOW, tr: makeTr("es") }),
      aiSummaryStamp("2026-10-14T14:42:00Z", { zone: ZONE, now: NOW, tr: makeTr("en") }),
      aiSummaryStamp("2026-10-14T14:42:00Z", { zone: ZONE, now: NOW, tr: makeTr("es") }),
    ]).toEqual([
      "Generated by AI · 9:42 AM", "Generado por IA · 9:42 a.m.",
      "Generated by AI · Oct 14, 9:42 AM", "Generado por IA · 14 oct, 9:42 a.m.",
    ]);
  });
  it("the pseudo-locale reaches the label (DoD; mutation: build it with t() instead of tr.text -> FAILS)", () => {
    expect(aiSummaryStamp("2026-10-18T14:42:00Z", { zone: ZONE, now: NOW, tr: makeTr("en", true) })).not.toBe("Generated by AI · 9:42 AM");
  });
});

describe("the response's shape (spec 4.2)", () => {
  it("passes the five states and refuses anything else (mutation: return v as AiSummaryResponse -> FAILS)", () => {
    const ready = { state: "ready", text: "Booked.", generatedAt: "2026-10-18T14:42:00Z", language: "es", stamp: "Generado por IA · 9:42 a.m." };
    expect(parseAiSummary(ready)).toEqual(ready);
    for (const s of ["generating", "none", "capped", "failed"]) expect(parseAiSummary({ state: s })).toEqual({ state: s });
    for (const bad of [null, {}, { state: "ready" }, { ...ready, language: "fr" }, { ...ready, text: 3 }, { state: "maybe" }]) expect(parseAiSummary(bad)).toEqual({ state: "failed" });
  });
});
