import type { Tr } from "./copy";

/**
 * The record summary's answer (spec 4.2; plan deviation 13), its label and the day's cap. No value import
 * from @bis/db or lib/ai: the record page's "use client" part imports this file's TYPES, and the Settings
 * view imports the cap.
 */
export const RECORD_SUMMARY_DAILY_CAP = 200;
export type AiSummaryResponse =
  | { state: "ready"; text: string; generatedAt: string; language: "en" | "es"; stamp: string }
  | { state: "generating" } | { state: "none" } | { state: "capped" } | { state: "failed" };

export function parseAiSummary(v: unknown): AiSummaryResponse {
  const r = v as Record<string, unknown> | null;
  if (r && typeof r === "object") {
    if (r.state === "ready" && typeof r.text === "string" && typeof r.generatedAt === "string"
        && (r.language === "en" || r.language === "es") && typeof r.stamp === "string") {
      return { state: "ready", text: r.text, generatedAt: r.generatedAt, language: r.language, stamp: r.stamp };
    }
    if (r.state === "generating" || r.state === "none" || r.state === "capped" || r.state === "failed") return { state: r.state };
  }
  return { state: "failed" };
}

const plain = (s: string) => s.replace(/[\u00A0\u202F]/g, " ");
const dayIn = (d: Date, zone: string) => new Intl.DateTimeFormat("en-CA", { timeZone: zone, year: "numeric", month: "2-digit", day: "2-digit" }).format(d);

/**
 * "Generated by AI · 9:42 AM", with the date when it was not written today (plan deviation 14), and the year
 * too when that is not this year (review M-4). "Today" and "this year" are the account's own, never UTC's.
 */
export function aiSummaryStamp(iso: string, o: { zone: string; now: Date; tr: Tr }): string {
  const at = new Date(iso);
  const tag = o.tr.locale === "es" ? "es-US" : "en-US";
  const written = dayIn(at, o.zone);
  const today = dayIn(o.now, o.zone);
  const time = plain(new Intl.DateTimeFormat(tag, written === today
    ? { timeZone: o.zone, hour: "numeric", minute: "2-digit" }
    : { timeZone: o.zone, ...(written.slice(0, 4) === today.slice(0, 4) ? {} : { year: "numeric" as const }), month: "short", day: "numeric", hour: "numeric", minute: "2-digit" }).format(at));
  return o.tr.text("record.ai.label", { time });
}
