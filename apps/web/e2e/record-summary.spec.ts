import { test, expect, type Page } from "./fixtures/test";
import { config as loadEnv } from "dotenv";
import { serviceDb, createContact, getOrCreateCalendar, createBooking } from "@bis/db";
import { readClientFixture, recordPage } from "./support";
import { m, type MessageKey } from "../src/lib/messages";

loadEnv({ path: "apps/web/.env.local" });
loadEnv({ path: ".env.local" });

test.describe.configure({ mode: "serial", timeout: 90_000 });

/**
 * Item 8a-2 (spec 8.4): the record's AI summary on the PER-RUN fixture account only (never Test Client One),
 * against AI_PROVIDER=fake (no model call). One customer with a booking and a document, made here and
 * deleted in afterAll (the booking first: bookings.contact_id is on delete restrict); the account's AI rows
 * are cleared before and after, so the counts read here are this spec's own. Spanish is the QA override
 * `?locale=es`. Words come from the catalogue.
 */
const stamp = Date.now();
const ACTOR = "e2e-record-summary";
let accountId = "";
const made: { contact?: string; booking?: string; document?: string } = {};
const w = (key: MessageKey, lang: "en" | "es" = "en", params: Record<string, string | number> = {}) => {
  const raw = (lang === "es" ? (m as Record<string, string>)[`${key}.es`] : undefined) ?? m[key];
  return Object.entries(params).reduce((s, [k, v]) => s.split(`{${k}}`).join(String(v)), raw);
};
const url = (q = "") => `/dashboard/accounts/${accountId}/contacts/${made.contact}${q}`;
const part = (page: Page) => recordPage(page).locator('[data-record-card="summary"] [data-ai-summary]');

async function cleanAi() {
  const db = serviceDb();
  for (const table of ["record_summaries", "ai_ledger", "account_ai_settings"]) {
    const { error } = await db.from(table).delete().eq("account_id", accountId);
    if (error) throw new Error(`record-summary e2e cleanup: ${table} failed: ${error.message}`);
  }
}
async function cacheRow(language: "en" | "es") {
  const { data, error } = await serviceDb().from("record_summaries").select("body, generated_at")
    .eq("account_id", accountId).eq("contact_id", made.contact!).eq("language", language).maybeSingle();
  if (error) throw new Error(`record-summary e2e: cache read failed: ${error.message}`);
  return data as { body: string | null; generated_at: string | null } | null;
}

test.beforeAll(async () => {
  const fixture = readClientFixture();
  if (!fixture) throw new Error("No client fixture: the setup project creates it; run the full suite.");
  accountId = fixture.accountId;
  await cleanAi();
  const db = serviceDb();
  const c = await createContact(db, accountId, { firstName: "Summary", lastName: `Spec ${stamp}` }, ACTOR);
  if (c.existing) throw new Error("record-summary e2e: the contact matched an existing one; refusing to use (or delete) it.");
  made.contact = c.id;
  const cal = await getOrCreateCalendar(db, accountId, ACTOR);
  const start = new Date(Date.now() + 60 * 86_400_000);
  start.setUTCHours(16, stamp % 60, 0, 0);
  made.booking = (await createBooking(db, accountId, {
    calendarId: cal.id, contactId: made.contact, startsAt: start, endsAt: new Date(start.getTime() + 3_600_000), ipHash: `e2e-rs-${stamp}`,
  }, ACTOR)).id;
  const { data: doc, error } = await db.from("documents").insert({
    account_id: accountId, contact_id: made.contact, title: `Insurance card ${stamp}`, category: "insurance", source: "upload", created_by: ACTOR,
  }).select("id").single();
  // This document has no version, so it is on no screen and NOT in the summary's inputs (final review I-2):
  // the booking above, 60 days out, is what gives the summary something to say.
  if (error) throw new Error(`record-summary e2e: document seed failed: ${error.message}`);
  made.document = (doc as { id: string }).id;
});

test.afterAll(async () => {
  if (!accountId) return;
  const db = serviceDb();
  const step = async (what: string, run: () => PromiseLike<{ error: { message: string } | null }>) => {
    const { error } = await run();
    if (error) throw new Error(`record-summary e2e cleanup: ${what} failed: ${error.message}`);
  };
  if (made.booking) await step("booking", () => db.from("bookings").delete().eq("account_id", accountId).eq("id", made.booking!));
  if (made.document) await step("document", () => db.from("documents").delete().eq("account_id", accountId).eq("id", made.document!));
  if (made.contact) await step("contact", () => db.from("contacts").delete().eq("account_id", accountId).eq("id", made.contact!));
  await cleanAi();
  for (const table of ["record_summaries", "ai_ledger", "account_ai_settings"]) {
    const { count, error } = await db.from(table).select("account_id", { count: "exact", head: true }).eq("account_id", accountId);
    if (error || count !== 0) throw new Error(`record-summary e2e cleanup: ${table} still holds ${count} rows (${error?.message ?? "no error"})`);
  }
});

test("the record writes a summary under the facts line, marked Generated by AI", async ({ page }) => {
  await page.goto(url());
  const p = part(page);
  await expect(p).toHaveAttribute("data-state", "ready", { timeout: 30_000 });
  await expect(p.locator("[data-ai-summary-text]")).toHaveText(/^\[fake en\] [0-9a-f]{8}$/);
  await expect(p.locator("[data-ai-summary-text]")).toHaveAttribute("lang", "en");
  await expect(p.locator("[data-ai-summary-label]")).toContainText(w("record.ai.label").split("{time}")[0]!.trim());
  await expect(recordPage(page).locator('[data-record-card="summary"] [data-record-facts]')).toBeVisible();
  expect((await cacheRow("en"))?.body).toMatch(/^\[fake en\] [0-9a-f]{8}$/);
});

test("Regenerate writes it again: a new time on the label", async ({ page }) => {
  await page.goto(url());
  const p = part(page);
  await expect(p).toHaveAttribute("data-state", "ready", { timeout: 30_000 });
  const before = await p.locator("[data-ai-summary-label]").getAttribute("data-generated-at");
  await p.locator("[data-ai-regenerate]").click();
  await expect(p).toHaveAttribute("data-state", "ready", { timeout: 30_000 });
  await expect.poll(async () => p.locator("[data-ai-summary-label]").getAttribute("data-generated-at")).not.toBe(before);
  expect((await cacheRow("en"))?.generated_at).not.toBeNull();
});

test("a Spanish reader gets the Spanish summary and the Spanish label", async ({ page }) => {
  await page.goto(url("?locale=es"));
  const p = part(page);
  await expect(p).toHaveAttribute("data-state", "ready", { timeout: 30_000 });
  await expect(p.locator("[data-ai-summary-text]")).toHaveText(/^\[fake es\] [0-9a-f]{8}$/);
  await expect(p.locator("[data-ai-summary-text]")).toHaveAttribute("lang", "es");
  await expect(p.locator("[data-ai-summary-label]")).toContainText(w("record.ai.label", "es").split("{time}")[0]!.trim());
  await expect(p.locator("[data-ai-regenerate]")).toHaveText(w("record.ai.regenerate", "es"));
});

test("the agency's AI card shows this month's spend and today's summaries", async ({ page }) => {
  const { data, error } = await serviceDb().from("account_ai_settings").select("record_summaries_today").eq("account_id", accountId).single();
  if (error) throw new Error(`record-summary e2e: settings read failed: ${error.message}`);
  const today = (data as { record_summaries_today: number }).record_summaries_today;
  // A Regenerate on unchanged inputs still counts: the row's first forced claim wins, and its write is a successful record_summary row.
  expect(today).toBe(3); // English on open, English on Regenerate, Spanish on open
  await page.goto(`/dashboard/accounts/${accountId}/settings#ai`);
  const card = page.locator("#ai[data-ai-card]");
  const lang = ((await card.getAttribute("lang")) === "es" ? "es" : "en") as "en" | "es";
  await expect(card.locator("[data-ai-spend]")).toHaveText(w("aiSettings.spend", lang, { spent: "$0.01", budget: "$10.00" }));
  await expect(card.locator("[data-ai-summaries]")).toHaveText(w("aiSettings.summariesToday", lang, { count: today, cap: 200 }));
});

test("with AI off for the account the record shows the facts line only; on again, the summary is back", async ({ page }) => {
  await page.goto(`/dashboard/accounts/${accountId}/settings#ai`);
  const card = page.locator("#ai[data-ai-card]");
  const lang = ((await card.getAttribute("lang")) === "es" ? "es" : "en") as "en" | "es";
  await card.locator("[data-ai-account]").click();
  await card.locator("[data-ai-save]").click();
  await expect(page.locator("[data-sonner-toast]").filter({ hasText: w("aiSettings.saved", lang) })).toBeVisible();
  const answered = page.waitForResponse(/\/ai-summary(\?|$)/);
  await page.goto(url());
  expect(await (await answered).json()).toEqual({ state: "none" });
  await expect(part(page)).toHaveCount(0);
  await expect(recordPage(page).locator('[data-record-card="summary"] [data-record-facts]')).toBeVisible();
  await page.goto(`/dashboard/accounts/${accountId}/settings#ai`);
  await card.locator("[data-ai-account]").click();
  await card.locator("[data-ai-save]").click();
  await expect(page.locator("[data-sonner-toast]").filter({ hasText: w("aiSettings.saved", lang) })).toBeVisible();
  await page.goto(url());
  await expect(part(page)).toHaveAttribute("data-state", "ready", { timeout: 30_000 });
});

test("at 360 px in the pseudo-locale the part does not overflow", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto(url("?locale=pseudo"));
  const p = part(page);
  await expect(p).toHaveAttribute("data-state", "ready", { timeout: 30_000 });
  const over = await p.evaluate((el) => [el, ...el.querySelectorAll("*")].filter((n) => (n as HTMLElement).scrollWidth > (n as HTMLElement).clientWidth + 1).length);
  expect(over).toBe(0);
});
